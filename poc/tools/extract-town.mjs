// Regenerates town.json from what the client actually builds (GAME-81).
// Starts this server on a spare port, loads the page in headless Chromium, calls
// window.__townDump() and merges it with the hand-kept parts of town.json
// (actions, the look-test props, spawn points). Needs Playwright with Chromium.
//
//   node tools/extract-town.mjs            # rewrites town.json
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const TOWN = path.join(ROOT, 'town.json');
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const old = JSON.parse(fs.readFileSync(TOWN, 'utf8'));
const port = 20000 + Math.floor(Math.random() * 20000);
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tw-extract-'));
const srv = spawn(process.execPath, ['server.mjs'], { cwd: ROOT, env: { ...process.env, PORT: String(port), DATA_FILE: path.join(tmp, 'save.json') }, stdio: ['ignore', 'pipe', 'inherit'] });
await new Promise((ok, bad) => { srv.stdout.on('data', d => { if (String(d).includes('listening')) ok(); }); srv.on('exit', c => bad(new Error('server exited ' + c))); });

const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
let dump;
try {
  const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://localhost:${port}/`);
  await page.waitForFunction(() => window.__townDump && window.__tw, null, { timeout: 180000 });
  if (errors.length) throw new Error('page errors:\n' + errors.join('\n'));
  dump = await page.evaluate(() => window.__townDump());
} finally { await browser.close(); srv.kill(); }

// Spawn points: the look-test ones plus one per district, kept only if nothing solid is there.
const inside = ([x, z], c, pad = 0.7) => {
  if (c.p[1] - (c.box ? c.box[1] : (c.cyl[1] / 2)) > 1.6) return false; // overhead (the Skyway deck)
  if (c.cyl) return Math.hypot(x - c.p[0], z - c.p[2]) < c.cyl[0] + pad;
  let dx = x - c.p[0], dz = z - c.p[2];
  if (c.q) { const yaw = 2 * Math.atan2(c.q[1], c.q[3]), cs = Math.cos(yaw), sn = Math.sin(yaw); [dx, dz] = [dx * cs - dz * sn, dx * sn + dz * cs]; }
  return Math.abs(dx) < c.box[0] + pad && Math.abs(dz) < c.box[2] + pad;
};
const candidates = [...old.spawnPoints.slice(0, 4), [-30, -6.2], [24, 40], [-22, 93], [6.3, 30], [-40, 6.2], [60, 6.2], [100, -70], [-60, -70], [96, 66], [44, -6.2]];
const spawnPoints = [];
for (const p of candidates) {
  const hit = dump.colliders.find(c => inside(p, c));
  if (hit) console.warn('spawn point', p, 'blocked by', JSON.stringify(hit)); else spawnPoints.push(p);
}

const lookProps = old.props.filter(p => !dump.newProps.some(n => n.id === p.id));
const town = {
  name: 'Puddlewick',
  note: 'Generated by tools/extract-town.mjs from what the client builds (look test + tools/town-build.js, GAME-81). Colliders, windows, piles and npcs are in client build order. roads/walks/lots/buildings/decks are axis-aligned rects for the mini map.',
  bounds: dump.bounds,
  spawn: old.spawn,
  spawnPoints,
  colliders: dump.colliders,
  windows: dump.windows,
  piles: dump.piles,
  props: [...lookProps, ...dump.newProps],
  npcs: dump.npcs,
  zones: dump.zones,
  actions: old.actions,
  traffic: dump.traffic,
  burnables: dump.burnables,
  roads: dump.roads, walks: dump.walks, lots: dump.lots, buildings: dump.buildings, decks: dump.decks,
};
fs.writeFileSync(TOWN, JSON.stringify(town));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`town.json: ${town.colliders.length} colliders, ${town.windows.length} windows, ${town.piles.length} piles, ${town.props.length} props, ${town.npcs.length} npcs, ${town.zones.length} zones, ${town.burnables.length} burnables, ${town.buildings.length} buildings, ${spawnPoints.length} spawn points`);
